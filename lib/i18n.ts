export function t(lang: Lang | any, key: string): string {
  const parts = key.split('.');
  // Always use 'en' regardless of input
  let cur: any = DICT.en;
  for (const p of parts) {
    cur = cur?.[p];
  }
  return typeof cur === 'string' ? cur : key;
}

